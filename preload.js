const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  openFiles: (kind, multi) => ipcRenderer.invoke('open-files', kind, multi),
  saveFile: (kind, name) => ipcRenderer.invoke('save-file', kind, name),
  pickFolder: def => ipcRenderer.invoke('pick-folder', def),
  videosDir: () => ipcRenderer.invoke('videos-dir'),
  reveal: p => ipcRenderer.invoke('reveal', p),
  readFile: p => ipcRenderer.invoke('read-file', p),
  readText: p => ipcRenderer.invoke('read-text', p),
  writeFile: (p, data) => ipcRenderer.invoke('write-file', p, data),
  writeText: (p, t) => ipcRenderer.invoke('write-text', p, t),
  makeTemp: () => ipcRenderer.invoke('make-temp'),
  removeDir: p => ipcRenderer.invoke('remove-dir', p),
  joinPath: (...a) => ipcRenderer.invoke('join-path', ...a),
  probe: p => ipcRenderer.invoke('probe', p),
  exists: p => ipcRenderer.invoke('exists', p),
  cacheDir: () => ipcRenderer.invoke('cache-dir'),
  projectsDir: () => ipcRenderer.invoke('projects-dir'),
  importMedia: p => ipcRenderer.invoke('import-media', p),
  mediaDir: () => ipcRenderer.invoke('media-dir'),
  renameProject: (p, name) => ipcRenderer.invoke('rename-project', p, name),
  memInfo: () => ipcRenderer.invoke('mem-info'),
  ffmpeg: (id, args, dur) => ipcRenderer.invoke('ffmpeg', id, args, dur),
  ffmpegCancel: id => ipcRenderer.invoke('ffmpeg-cancel', id),
  onProgress: cb => ipcRenderer.on('ffmpeg-progress', (_, id, p) => cb(id, p)),
  pathForFile: f => webUtils.getPathForFile(f),
  secretGet: n => ipcRenderer.invoke('secret-get', n),
  secretSet: (n, v) => ipcRenderer.invoke('secret-set', n, v),
  httpJson: (url, opts) => ipcRenderer.invoke('http-json', url, opts),
  httpFile: (url, opts, out) => ipcRenderer.invoke('http-file', url, opts, out),
  httpStream: (id, url, opts) => ipcRenderer.invoke('http-stream', id, url, opts),
  httpAbort: id => ipcRenderer.invoke('http-abort', id),
  onHttpChunk: cb => ipcRenderer.on('http-chunk', (_, id, t) => cb(id, t)),
  writeBase64: (p, b64) => ipcRenderer.invoke('write-base64', p, b64),
  mkdirp: p => ipcRenderer.invoke('mkdirp', p),
  imageToJpeg: (src, out) => ipcRenderer.invoke('image-to-jpeg', src, out),
  docText: p => ipcRenderer.invoke('doc-text', p),
  copyFile: (src, dest) => ipcRenderer.invoke('copy-file', src, dest),
  readBase64: p => ipcRenderer.invoke('read-base64', p),
  openExternal: url => ipcRenderer.invoke('open-external', url),
  clipboardWrite: t => ipcRenderer.invoke('clipboard-write', t),
  downloadsWatch: on => ipcRenderer.invoke('downloads-watch', on),
  onDownload: cb => ipcRenderer.on('download-added', (_, p) => cb(p)),
});
